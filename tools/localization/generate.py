#!/usr/bin/env python3
"""Render reviewed translation tables into Android resources; never silently copy English."""
from pathlib import Path
from xml.sax.saxutils import escape
import xml.etree.ElementTree as ET
import re

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / 'app/src/main/res'
LANGS = ['es', 'pt-BR', 'fr', 'ja', 'ko', 'hi', 'id', 'ar']
DIRS = {'pt-BR': 'pt-rBR', 'id': 'in'}

def table(path, langs):
    maps = {lang: {} for lang in langs}
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not line or line.startswith('#'): continue
        parts = line.split('|')
        assert len(parts) == len(langs) + 1, (path, number, len(parts))
        key = parts[0]
        for lang, value in zip(langs, parts[1:]):
            assert key not in maps[lang], (lang, key, 'duplicate')
            assert value.strip(), (lang, key, 'empty')
            maps[lang][key] = value
    return maps

def read(path):
    return {e.attrib['name']: e.text or '' for e in ET.parse(path).getroot() if e.tag == 'string'}

def placeholders(value): return sorted(re.findall(r'%\d+\$[dsf]', value))

def generate():
    source = read(RES/'values/strings.xml')
    maps = table(Path(__file__).with_name('catalog.tsv'), LANGS)
    for lang, new in table(Path(__file__).with_name('services-de-nl.tsv'), ['de', 'nl']).items():
        maps[lang] = read(RES/f'values-{lang}/strings.xml') | new
    for lang, strings in maps.items():
        assert strings.keys() == source.keys(), (lang, 'missing', source.keys()-strings.keys(), 'extra', strings.keys()-source.keys())
        for key, text in strings.items():
            assert placeholders(text) == placeholders(source[key]), (lang, key, 'format mismatch')
        path = RES / ('values-' + DIRS.get(lang, lang)) / 'strings.xml'
        path.parent.mkdir(exist_ok=True)
        def android(text): return escape(text).replace("\\'", "'").replace("'", "\\'").replace('"', '\\"')
        path.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/localization/generate.py -->\n<resources>\n' +
            ''.join(f'    <string name="{key}">{android(strings[key])}</string>\n' for key in source) + '</resources>\n')
    print(f'Generated {len(source)} strings in {len(maps)} locales; placeholders verified.')

if __name__ == '__main__': generate()
